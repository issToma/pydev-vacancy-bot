import os

# Фильтры поиска для веб-версии hh.ru (https://hh.ru/search/vacancy).
# Значения-списки превращаются в повторяющиеся query-параметры (area=113&area=40&...).
SEARCH_FILTERS = {
    "text": "Python",
    "search_field": ["name"],          # искать только в названии вакансии
    "employment": "full",              # занятость: полный рабочий день
    "schedule": "fullDay",             # график: полный день
    "search_period": "30",             # за последние 30 дней
    "items_on_page": "100",            # вакансий на странице (20/50/100)
}

# --- Настройки запуска браузера ---

# Видимый браузер (headed) позволяет вручную пройти капчу.
# В Celery-воркере капчу пройти нельзя → по умолчанию headless.
HEADLESS = os.getenv("HH_HEADLESS", "1") == "1"

# Сколько страниц выдачи обходить максимум (по 100 вакансий на странице).
MAX_PAGES = int(os.getenv("HH_MAX_PAGES", "5"))

# Человеческая пауза между действиями, секунды (чтобы не нагружать сайт).
MIN_DELAY = 1.5
MAX_DELAY = 3.5

# Таймаут навигации, мс.
NAV_TIMEOUT_MS = 45000

# Размер батча инкрементальной записи в БД (сохраняем по ходу сбора).
BATCH_SIZE = int(os.getenv("HH_BATCH_SIZE", "10"))

# Сколько ждать ручного прохождения капчи в headed-режиме, секунды.
CAPTCHA_WAIT_SECONDS = 180