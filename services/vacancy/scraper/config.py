import os

# Фильтры поиска для веб-версии hh.ru (https://hh.ru/search/vacancy).
# Значения-списки превращаются в повторяющиеся query-параметры (area=113&area=40&...).
SEARCH_FILTERS = {
    "text": "Python",
    "search_field": ["name"],          # искать только в названии вакансии
    "employment": "full",              # занятость: полный рабочий день
    "schedule": "fullDay",             # график: полный день
    "search_period": "30",             # за последние 30 дней
    "order_by": "publication_time",    # сортировка по дате (свежие сверху): при потолке
                                       # MAX_PAGES*items новые вакансии не теряются в хвосте
    "items_on_page": "100",            # вакансий на странице (20/50/100)
}

# --- Настройки запуска браузера ---

# По умолчанию headless (без окна) — на hh.ru работает нормально (проверено:
# так собраны боевые данные). Пустая выдача бывает из-за VPN, а не из-за headless.
# Если понадобится пройти капчу вручную — HH_HEADLESS=0 (откроется окно).
HEADLESS = os.getenv("HH_HEADLESS", "1") == "1"

# Сколько страниц выдачи обходить максимум (по 100 вакансий на странице).
# 7 → потолок 700 вакансий (шаг сотнями = items_on_page). Хватает на весь наш
# отфильтрованный набор (~500+) с запасом; при сортировке по дате хвост — самые
# старые вакансии окна, они уже собраны, так что рост потолка = разовый добор.
MAX_PAGES = int(os.getenv("HH_MAX_PAGES", "7"))

# Человеческая пауза между действиями, секунды (чтобы не нагружать сайт).
MIN_DELAY = 1.5
MAX_DELAY = 3.5

# Таймаут навигации, мс.
NAV_TIMEOUT_MS = 45000

# Размер батча инкрементальной записи в БД (сохраняем по ходу сбора).
BATCH_SIZE = int(os.getenv("HH_BATCH_SIZE", "10"))

# Пересоздавать контекст браузера каждые N детальных страниц: Firefox копит
# память по ходу навигаций, пересоздание контекста освобождает её. 0 — выключить.
RECYCLE_EVERY = int(os.getenv("HH_RECYCLE_EVERY", "50"))

# Мягкий лимит времени одного прогона, секунды. Держим МЕНЬШЕ жёсткого Celery
# task_time_limit (600с): при большом доборе прогон выходит по дедлайну штатно
# (дописав батч, закрыв браузер, отпустив лок), а остаток доберёт следующий тик —
# так избегаем SIGKILL по hard-лимиту. 0 — без ограничения.
MAX_RUN_SECONDS = int(os.getenv("HH_MAX_RUN_SECONDS", "480"))

# Сколько ждать ручного прохождения капчи в headed-режиме, секунды.
CAPTCHA_WAIT_SECONDS = 180